 *
 * These tests mirror `apps/mobile/tests/pin-codec.test.ts` on the TS side,
 * ensuring both layers agree on the same SPKI digest → pin format.
 *
 * The test vectors cover:
 *  - Known SHA-256 SPKI digests (hex → Base64 round-trip)
 *  - Fail-closed behavior: empty, wrong-length, non-hex pins throw PinCodecError
 *  - The `sha256/<base64>` format OkHttp expects (not `sha256/<hex>=`)
 */
