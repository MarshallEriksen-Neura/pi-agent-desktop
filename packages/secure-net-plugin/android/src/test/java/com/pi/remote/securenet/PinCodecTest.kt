    // ------------------------------------------------------------------
    // formatOkHttpPin — the core conversion
    // ------------------------------------------------------------------

    @Test
    fun `formatOkHttpPin converts all-zeros hex to correct sha256-slash-base64`() {
        val pin = PinCodec.formatOkHttpPin(ZERO_HEX)
        assertEquals(ZERO_OKHTTP_PIN, pin)
        assertTrue(pin.startsWith("sha256/"))
    }

    @Test
    fun `formatOkHttpPin converts sample hex to correct base64`() {
        val pin = PinCodec.formatOkHttpPin(SAMPLE_HEX)
        assertEquals(SAMPLE_OKHTTP_PIN, pin)
    }

    @Test
    fun `Rust certificate fixture is accepted by the SPKI trust manager`() {
        val certificate = rustCertificateFixture()
        val manager = SpkiPinTrustManager(PinCodec.hexToBytes(RUST_CERT_PIN_HEX))

        manager.checkServerTrusted(arrayOf(certificate), "ECDHE_ECDSA")
    }

    @Test(expected = PinMismatchException::class)
    fun `SPKI trust manager rejects a different QR pin`() {
        val certificate = rustCertificateFixture()
        val manager = SpkiPinTrustManager(ByteArray(32))

        manager.checkServerTrusted(arrayOf(certificate), "ECDHE_ECDSA")
    }

    @Test(expected = PinMismatchException::class)
    fun `SPKI trust manager rejects attacker leaf even when pinned cert is appended`() {
        val pinnedCertificate = rustCertificateFixture()
        val attackerCertificate = certificateFixture(ATTACKER_CERT_DER_BASE64)
        val manager = SpkiPinTrustManager(PinCodec.hexToBytes(RUST_CERT_PIN_HEX))

        manager.checkServerTrusted(
            arrayOf(attackerCertificate, pinnedCertificate),
            "ECDHE_RSA",
        )
    }

    @Test
    fun `nested TLS pin failure keeps actionable expected and peer pins`() {
        val certificate = rustCertificateFixture()
        val manager = SpkiPinTrustManager(ByteArray(32))
        val mismatch = try {
            manager.checkServerTrusted(arrayOf(certificate), "ECDHE_ECDSA")
            error("should have rejected mismatched pin")
        } catch (e: PinMismatchException) {
            e
        }
        val wrapped = javax.net.ssl.SSLHandshakeException("handshake failed").apply {
            initCause(mismatch)
        }

        val detail = pinMismatchDetail(wrapped)
        assertTrue(detail?.contains("expected sha256/") == true)
        assertTrue(detail?.contains("peer sha256/") == true)
    }

    @Test
    fun `endpoint pin keys are scoped by host and port and accept WSS`() {
        assertEquals(
            EndpointKey("192.168.31.199", 8443),
            EndpointKey.fromUrl("https://192.168.31.199:8443/health"),
        )
        assertEquals(
            EndpointKey("192.168.31.199", 8443),
            EndpointKey.fromUrl("wss://192.168.31.199:8443/v1/events"),
        )
        assertNotEquals(
            EndpointKey.fromParts("192.168.31.199", 8443),
            EndpointKey.fromParts("192.168.31.199", 9443),
        )
    }

    @Test
    fun `endpoint pin keys reject cleartext and invalid ports`() {
        assertEquals(null, EndpointKey.fromUrl("http://192.168.31.199:8443/health"))
        assertEquals(null, EndpointKey.fromUrl("ws://192.168.31.199:8443/v1/events"))
        assertEquals(null, EndpointKey.fromParts("192.168.31.199", 0))
    }

    @Test
    fun `formatOkHttpPin never uses the naive sha256-slash-hex hack`() {
        // The old broken approach was "sha256/<hex>=" which never matches a
        // real certificate. The correct output is "sha256/<base64>".
        val pin = PinCodec.formatOkHttpPin(ZERO_HEX)
        assertNotEquals("sha256/$ZERO_HEX=", pin)
        assertNotEquals("sha256/$ZERO_HEX", pin)
    }

    // ------------------------------------------------------------------
    // hexToBytes — decoding
    // ------------------------------------------------------------------

    @Test
    fun `hexToBytes decodes 64-char hex to 32 bytes`() {
        val bytes = PinCodec.hexToBytes(ZERO_HEX)
        assertEquals(32, bytes.size)
        bytes.forEach { assertEquals(0.toByte(), it) }
    }

    @Test
    fun `hexToBytes decodes sample hex correctly`() {
        val bytes = PinCodec.hexToBytes(SAMPLE_HEX)
        assertEquals(32, bytes.size)
        // First byte: 0x5d = 93
        assertEquals(0x5d.toByte(), bytes[0])
        // Second byte: 0xbe = 190
        assertEquals(0xbe.toByte(), bytes[1])
    }

    // ------------------------------------------------------------------
    // Fail-closed validation
    // ------------------------------------------------------------------

    @Test(expected = PinCodecError::class)
    fun `rejects empty pin`() {
        PinCodec.hexToBytes("")
    }

    @Test
    fun `empty pin has 'empty' error code`() {
        try {
            PinCodec.hexToBytes("")
            error("should have thrown")
        } catch (e: PinCodecError) {
            assertEquals("empty", e.code)
        }
    }

    @Test(expected = PinCodecError::class)
    fun `rejects wrong-length pin`() {
        PinCodec.hexToBytes("abc123") // 6 chars, not 64
    }

    @Test
    fun `wrong-length pin has 'invalid_length' error code`() {
        try {
            PinCodec.hexToBytes("abc123")
            error("should have thrown")
        } catch (e: PinCodecError) {
            assertEquals("invalid_length", e.code)
        }
    }

    @Test(expected = PinCodecError::class)
    fun `rejects non-hex characters`() {
        val badHex = "g".repeat(64) // 'g' is not a hex char
        PinCodec.hexToBytes(badHex)
    }

    @Test
    fun `non-hex pin has 'invalid_chars' error code`() {
        try {
            PinCodec.hexToBytes("g".repeat(64))
            error("should have thrown")
        } catch (e: PinCodecError) {
            assertEquals("invalid_chars", e.code)
        }
    }

    // ------------------------------------------------------------------
    // isValidHexPin
    // ------------------------------------------------------------------

    @Test
    fun `isValidHexPin returns true for valid 64-char hex`() {
        assertTrue(PinCodec.isValidHexPin(ZERO_HEX))
        assertTrue(PinCodec.isValidHexPin(SAMPLE_HEX))
    }

    @Test
    fun `isValidHexPin returns false for invalid pins without throwing`() {
        assertFalse(PinCodec.isValidHexPin(""))
        assertFalse(PinCodec.isValidHexPin("abc"))
        assertFalse(PinCodec.isValidHexPin("g".repeat(64)))
    }

    // ------------------------------------------------------------------
    // Case insensitivity
    // ------------------------------------------------------------------

    @Test
    fun `accepts uppercase hex (case-insensitive)`() {
        val upperHex = "A".repeat(64)
        val lowerHex = "a".repeat(64)
        val upperPin = PinCodec.formatOkHttpPin(upperHex)
        val lowerPin = PinCodec.formatOkHttpPin(lowerHex)
        // Both should produce the same Base64 (0xAA... = same bytes)
        assertEquals(upperPin, lowerPin)
    }

    @Test
    fun `mixed-case hex decodes correctly`() {
        val mixedHex = "AbCdEf".repeat(10) + "AbCd" // 64 chars
        val bytes = PinCodec.hexToBytes(mixedHex)
        assertEquals(32, bytes.size)
        // First byte: 0xAB = 171
        assertEquals(0xAB.toByte(), bytes[0])
    }

    private fun rustCertificateFixture(): X509Certificate {
        return certificateFixture(RUST_CERT_DER_BASE64)
    }

    private fun certificateFixture(derBase64: String): X509Certificate {
        val der = Base64.getDecoder().decode(derBase64)
        return CertificateFactory.getInstance("X.509")
            .generateCertificate(ByteArrayInputStream(der)) as X509Certificate
    }
